/* MY EDITOR V106 — continuous bidirectional page flow */
(() => {
  function installV106Pagination(){
    const $id=id=>document.getElementById(id);
    const ed=$id("editor");
    if(!ed || typeof current!=="function" || typeof extractOverflowChunks!=="function")return;

    let running=false;
    let timer=null;

    function isContinuation(page){
      return !!page?.autoGenerated && !page.title && !page.subtitle;
    }

    function saveLivePage(){
      const s=current();
      const p=s.pages[s.currentPageIndex];
      if(!p)return;
      const title=$id("titleInput"), subtitle=$id("subtitleInput");
      if(title)p.title=title.value;
      if(subtitle)p.subtitle=subtitle.value;
      p.content=ed.innerHTML;
      s.updatedAt=new Date().toISOString();
    }

    function rootIndexFor(slot,index){
      let i=Math.max(0,Math.min(index,slot.pages.length-1));
      while(i>0 && isContinuation(slot.pages[i]))i--;
      return i;
    }

    function chainEndFor(slot,root){
      let i=root+1;
      while(i<slot.pages.length && isContinuation(slot.pages[i]))i++;
      return i;
    }

    function loadPageForMeasure(slot,index){
      const p=slot.pages[index];
      slot.currentPageIndex=index;
      $id("titleInput").value=p.title||"";
      $id("subtitleInput").value=p.subtitle||"";
      ed.innerHTML=p.content||"";
      if(typeof applyTypography==="function")applyTypography();
      if(typeof applyDocumentLayout==="function")applyDocumentLayout();
      if(typeof normalizeEditorTopLevel==="function")normalizeEditorTopLevel();
      // Force layout flush before scroll/client measurements.
      void ed.offsetHeight;
    }

    function cleanEmptyTail(slot,root){
      let end=chainEndFor(slot,root);
      for(let i=end-1;i>root;i--){
        const p=slot.pages[i];
        const plain=typeof strip==="function"?strip(p.content||""):(p.content||"").replace(/<[^>]*>/g,"");
        if(isContinuation(p) && !plain.trim())slot.pages.splice(i,1);
        else break;
      }
    }

    function reflowContinuousChain(options={}){
      if(running || isPaginating)return false;
      const slot=current();
      if(!slot?.pages?.length)return false;

      saveLivePage();

      const originalIndex=Math.max(0,Math.min(slot.currentPageIndex||0,slot.pages.length-1));
      const root=rootIndexFor(slot,originalIndex);
      const originalOffset=originalIndex-root;
      const oldEnd=chainEndFor(slot,root);
      const oldCount=oldEnd-root;
      const wasOverflowing=typeof editorOverflows==="function" ? editorOverflows() : false;

      // One canonical source string for the whole auto-generated chain.
      let combined="";
      for(let i=root;i<oldEnd;i++)combined+=slot.pages[i].content||"";

      const rootPage=slot.pages[root];
      // Remove every old generated continuation. They will be rebuilt from the canonical flow.
      slot.pages.splice(root+1,oldEnd-root-1);
      rootPage.content=combined;

      running=true;
      isPaginating=true;
      let created=0;
      try{
        let index=root;
        let carry=combined;
        while(true){
          const page=slot.pages[index];
          page.content=carry;
          loadPageForMeasure(slot,index);

          const moved=extractOverflowChunks();
          page.content=ed.innerHTML;
          if(!moved.length)break;

          carry=moved.join("");
          const next=newPage(index+2,true);
          next.title="";
          next.subtitle="";
          next.content=carry;
          next.pageTypography={};
          next.pageDecorations=[];
          slot.pages.splice(index+1,0,next);
          created++;
          index++;

          // Hard safety guard against malformed content / impossible layouts.
          if(created>200){
            console.error("v106 pagination aborted: safety limit reached");
            break;
          }
        }

        cleanEmptyTail(slot,root);
        if(typeof renumberPages==="function")renumberPages();

        const newEnd=chainEndFor(slot,root);
        const newCount=newEnd-root;
        let restoreIndex=root+Math.min(originalOffset,Math.max(0,newCount-1));

        // When typing at the end causes overflow, continue naturally on the newly created page.
        if(options.fromInput && wasOverflowing && originalOffset===Math.max(0,oldCount-1) && newCount>oldCount){
          restoreIndex=Math.min(newEnd-1,root+originalOffset+1);
        }

        slot.currentPageIndex=Math.max(root,Math.min(restoreIndex,slot.pages.length-1));
        if(typeof persist==="function")persist();
        if(created>0 && newCount>oldCount && typeof showPageAddedNotice==="function")showPageAddedNotice();
      }catch(err){
        console.error("v106 continuous pagination failed",err);
      }finally{
        isPaginating=false;
        running=false;
        if(typeof renderAll==="function")renderAll();
      }
      return true;
    }

    // This becomes the single authoritative whole-document reflow entry point.
    window.reflowAllAutoPagesFromCurrentSlot = reflowAllAutoPagesFromCurrentSlot = function(){
      const slot=current();
      if(!slot?.pages?.length || running || isPaginating)return;
      saveLivePage();

      // Reflow each independent root chain from left to right. Manual pages with their own
      // title/subtitle remain independent; generated continuation pages belong to their root.
      let root=0;
      const originalIndex=slot.currentPageIndex||0;
      try{
        while(root<slot.pages.length){
          slot.currentPageIndex=root;
          loadPageForMeasure(slot,root);
          reflowContinuousChain({fromInput:false});
          root=chainEndFor(slot,root);
        }
      }finally{
        slot.currentPageIndex=Math.min(originalIndex,slot.pages.length-1);
        if(typeof persist==="function")persist();
        if(typeof renderAll==="function")renderAll();
      }
    };

    function schedule(fromInput=false,delay=260){
      clearTimeout(timer);
      timer=setTimeout(()=>requestAnimationFrame(()=>reflowContinuousChain({fromInput})),delay);
    }

    // Reflow on EVERY edit, not only delete. This is what makes text move both directions.
    ed.addEventListener("input",()=>schedule(true,220));
    $id("titleInput")?.addEventListener("input",()=>schedule(false,260));
    $id("subtitleInput")?.addEventListener("input",()=>schedule(false,260));

    // Layout/typography changes alter page capacity, so they also require a full flow pass.
    document.addEventListener("change",e=>{
      if(e.target?.closest?.("#tab-document,#tab-text,.panel-body,.right-panel"))schedule(false,300);
    });
    document.addEventListener("input",e=>{
      if(e.target===ed || e.target===$id("titleInput") || e.target===$id("subtitleInput"))return;
      if(e.target?.matches?.('input[type="range"],input[type="number"]'))schedule(false,300);
    });

    // Make sure old saved chains are normalized once after startup.
    setTimeout(()=>{
      try{reflowAllAutoPagesFromCurrentSlot()}catch(e){console.error(e)}
    },700);
  }

  // Load after base script + earlier hotfix DOMContentLoaded handlers have finished.
  if(document.readyState==="loading"){
    document.addEventListener("DOMContentLoaded",()=>setTimeout(installV106Pagination,0),{once:true});
  }else{
    setTimeout(installV106Pagination,0);
  }
})();
