/* MY EDITOR V106/V116 — single continuous page flow + persistent logical caret */
(() => {
  function installContinuousPagination(){
    const $id=id=>document.getElementById(id);
    const ed=$id('editor');
    if(!ed || typeof current!=='function' || typeof extractOverflowChunks!=='function')return;

    let running=false,timer=null,pendingCaret=null,restoreToken=0;
    try{if(typeof handleEditorInput==='function')ed.removeEventListener('input',handleEditorInput)}catch{}

    /* Heading mirroring must never break the document flow identity. */
    const isContinuation=page=>!!page?.autoGenerated;
    function plainLength(html){
      if(typeof strip==='function')return strip(html||'').length;
      const box=document.createElement('div');box.innerHTML=html||'';return (box.textContent||'').length;
    }
    function caretOffset(){
      const sel=getSelection();if(!sel?.rangeCount)return null;
      const r=sel.getRangeAt(0);if(!ed.contains(r.startContainer))return null;
      const pre=r.cloneRange();pre.selectNodeContents(ed);pre.setEnd(r.startContainer,r.startOffset);return pre.toString().length;
    }
    function restoreCaret(offset,token){
      if(token!==restoreToken)return false;
      offset=Math.max(0,Number(offset)||0);
      const walker=document.createTreeWalker(ed,NodeFilter.SHOW_TEXT);
      let total=0,node,last=null;
      while((node=walker.nextNode())){
        last=node;const len=node.nodeValue.length;
        if(offset<=total+len){
          const range=document.createRange();range.setStart(node,Math.max(0,offset-total));range.collapse(true);
          const sel=getSelection();sel.removeAllRanges();sel.addRange(range);
          try{savedRange=range.cloneRange()}catch{}
          ed.focus({preventScroll:true});return true;
        }
        total+=len;
      }
      const range=document.createRange();range.selectNodeContents(ed);range.collapse(false);
      const sel=getSelection();sel.removeAllRanges();sel.addRange(range);
      try{savedRange=range.cloneRange()}catch{}
      ed.focus({preventScroll:true});return true;
    }
    function saveLive(){
      const s=current(),p=s.pages?.[s.currentPageIndex||0];if(!p)return;
      if($id('titleInput'))p.title=$id('titleInput').value;
      if($id('subtitleInput'))p.subtitle=$id('subtitleInput').value;
      p.content=ed.innerHTML;s.updatedAt=new Date().toISOString();
    }
    function rootIndex(slot,index){
      let i=Math.max(0,Math.min(index,slot.pages.length-1));
      while(i>0&&isContinuation(slot.pages[i]))i--;
      return i;
    }
    function chainEnd(slot,root){let i=root+1;while(i<slot.pages.length&&isContinuation(slot.pages[i]))i++;return i}
    function logicalMarker(){
      const slot=current(),index=slot.currentPageIndex||0,root=rootIndex(slot,index),local=caretOffset();
      if(local==null)return null;
      let absolute=local;for(let i=root;i<index;i++)absolute+=plainLength(slot.pages[i].content||'');
      return {rootId:slot.pages[root]?.id,absolute};
    }
    function loadForMeasure(slot,index){
      const p=slot.pages[index];slot.currentPageIndex=index;
      if($id('titleInput'))$id('titleInput').value=p.title||'';
      if($id('subtitleInput'))$id('subtitleInput').value=p.subtitle||'';
      ed.innerHTML=p.content||'';
      try{applyTypography?.()}catch{};try{applyDocumentLayout?.()}catch{};try{normalizeEditorTopLevel?.()}catch{};
      void ed.offsetHeight;
    }
    function targetForMarker(slot,root,marker){
      if(!marker)return null;
      let remaining=Math.max(0,marker.absolute),end=chainEnd(slot,root);
      for(let i=root;i<end;i++){
        const len=plainLength(slot.pages[i].content||'');
        if(remaining<=len||i===end-1)return {index:i,offset:Math.min(remaining,len)};
        remaining-=len;
      }
      return {index:root,offset:0};
    }
    function finish(slot,index,offset=null){
      slot.currentPageIndex=Math.max(0,Math.min(index,slot.pages.length-1));
      try{persist?.()}catch{};try{renderAll?.()}catch{}
      if(offset!=null){
        const token=++restoreToken;
        requestAnimationFrame(()=>requestAnimationFrame(()=>requestAnimationFrame(()=>restoreCaret(offset,token))));
      }
    }

    function reflowChain({marker=null,announce=true}={}){
      if(running||isPaginating)return false;
      const slot=current();if(!slot?.pages?.length)return false;
      saveLive();
      const original=Math.max(0,Math.min(slot.currentPageIndex||0,slot.pages.length-1));
      const root=rootIndex(slot,original),oldEnd=chainEnd(slot,root),oldCount=oldEnd-root;

      /* Pull every continuation page back into one canonical stream first. This is what
         guarantees that free space on an earlier page is filled from later pages. */
      let combined='';for(let i=root;i<oldEnd;i++)combined+=slot.pages[i].content||'';
      const rootPage=slot.pages[root];
      slot.pages.splice(root+1,Math.max(0,oldEnd-root-1));
      rootPage.content=combined;

      running=true;isPaginating=true;let created=0;
      try{
        let index=root,carry=combined;
        while(true){
          const page=slot.pages[index];page.content=carry;loadForMeasure(slot,index);
          const moved=extractOverflowChunks();page.content=ed.innerHTML;
          if(!moved.length)break;
          carry=moved.join('');
          const next=newPage(index+2,true);
          next.autoGenerated=true;next.title=rootPage.title||'';next.subtitle=rootPage.subtitle||'';next.content=carry;
          next.pageTypography={};next.pageDecorations=[];
          slot.pages.splice(index+1,0,next);created++;index++;
          if(created>200){console.error('pagination safety limit');break}
        }
        /* remove empty generated tail pages */
        let end=chainEnd(slot,root);
        for(let i=end-1;i>root;i--){if(isContinuation(slot.pages[i])&&!plainLength(slot.pages[i].content||''))slot.pages.splice(i,1);else break}
        try{renumberPages?.()}catch{}
        const target=targetForMarker(slot,root,marker),newCount=chainEnd(slot,root)-root;
        const restoreIndex=target?.index??Math.min(original,slot.pages.length-1);
        if(announce&&created>0&&newCount>oldCount)try{showPageAddedNotice?.()}catch{}
        isPaginating=false;running=false;finish(slot,restoreIndex,target?.offset??null);return true;
      }catch(err){
        console.error('continuous pagination failed',err);isPaginating=false;running=false;
        const target=targetForMarker(slot,root,marker);finish(slot,target?.index??Math.min(original,slot.pages.length-1),target?.offset??null);return false;
      }
    }

    /* Any delayed caller (including old compatibility patches) now preserves the live caret.
       When the editor is focused, only its current document chain is rebuilt. */
    window.reflowAllAutoPagesFromCurrentSlot=reflowAllAutoPagesFromCurrentSlot=function(){
      if(running||isPaginating)return;
      const slot=current();if(!slot?.pages?.length)return;
      saveLive();
      const focused=ed.contains(document.activeElement)||document.activeElement===ed||caretOffset()!=null;
      const marker=focused?logicalMarker():null;
      if(marker){reflowChain({marker,announce:false});return}

      const original=slot.currentPageIndex||0;
      let root=0;
      while(root<slot.pages.length){
        slot.currentPageIndex=root;loadForMeasure(slot,root);
        reflowChain({marker:null,announce:false});
        root=chainEnd(slot,root);
      }
      finish(slot,Math.min(original,slot.pages.length-1),null);
    };

    function schedule(marker=null,delay=80){
      clearTimeout(timer);if(marker)pendingCaret=marker;
      timer=setTimeout(()=>requestAnimationFrame(()=>{const m=pendingCaret;pendingCaret=null;reflowChain({marker:m,announce:true})}),delay);
    }
    ed.addEventListener('input',()=>{
      saveLive();const marker=logicalMarker();pendingCaret=marker;
      try{persist?.();updateCount?.();renderSlots?.()}catch{}
      schedule(marker,65);
    });
    $id('titleInput')?.addEventListener('input',()=>{saveLive();try{persist?.()}catch{};schedule(null,130)});
    $id('subtitleInput')?.addEventListener('input',()=>{saveLive();try{persist?.()}catch{};schedule(null,130)});
    document.addEventListener('change',e=>{if(e.target?.closest?.('.panel-body,.right-panel'))schedule(null,180)});
    document.addEventListener('input',e=>{if(e.target===ed||e.target===$id('titleInput')||e.target===$id('subtitleInput'))return;if(e.target?.matches?.('input[type="range"],input[type="number"]'))schedule(null,180)});
    setTimeout(()=>{try{reflowAllAutoPagesFromCurrentSlot()}catch(e){console.error(e)}},700);
  }
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',()=>setTimeout(installContinuousPagination,0),{once:true});else setTimeout(installContinuousPagination,0);
})();
